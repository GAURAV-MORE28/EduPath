"""
EduPath domain knowledge pack — validation script.

Validates the invariants required by design doc §11.5 and
ARCHITECTURE_CONTRACTS.md §5 against the JSON files under data/dataset/
(generated by build_dataset.py). Run after every regeneration:

    python data/scripts/build_dataset.py
    python data/scripts/validate_dataset.py

Exit code 0 = no hard errors (warnings may still be printed).
Exit code 1 = at least one hard error (would block the graph from loading).

Checks performed:
  1.  Duplicate IDs within each entity collection.
  2.  Missing references: skill edges, role requirements, resource skill
      targets/prerequisites, misconception skill/root refs, assessment item
      skill/misconception refs, demo dataset refs.
  3.  Hard-prerequisite graph must be a DAG (cycle check).
  4.  Orphan skills (no edge, no role requirement, no resource, no item —
      i.e. completely disconnected from the rest of the graph).
  5.  Every role-required skill has >= 1 catalog resource (warning, not hard
      error, if not).
  6.  Every misconception has an affected_skill and root_prerequisite that
      both resolve, and the root is a real (transitive) hard-prerequisite
      ancestor of the affected skill in the curated graph.
  7.  Every assessment item's skill_id and (if set) misconception_id resolve.
  8.  Resource URLs: well-formed https URLs; flags anything not on an
      allowlist of reputable domains for manual re-review (soft check —
      this script cannot make live network calls in this environment; see
      README.md for how to run the optional live link-check pass).
  9.  Assessable-skill item-bank coverage report (informational): which
      assessable skills have 0 / <6 / >=6 items. This is NOT a hard failure
      for this phase — see IMPLEMENTATION_STATE.md "Data Assets Status" for
      why full coverage is intentionally deferred.
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
DATASET = ROOT / "dataset"

ERRORS: list[str] = []
WARNINGS: list[str] = []


def err(msg):
    ERRORS.append(msg)


def warn(msg):
    WARNINGS.append(msg)


def load(name):
    return json.loads((DATASET / name).read_text(encoding="utf-8"))


def check_duplicates(items, key, label):
    seen = {}
    for it in items:
        k = it[key]
        if k in seen:
            err(f"Duplicate {label} id: {k!r}")
        seen[k] = it


def main():
    if not DATASET.exists():
        print(f"Dataset directory not found: {DATASET}. Run build_dataset.py first.")
        sys.exit(1)

    skills = load("skills.json")
    roles = load("roles.json")
    edges = load("skill_edges.json")
    resources = load("resources.json")
    misconceptions = load("misconceptions.json")
    items = load("assessment_items.json")

    skill_ids = {s["skill_id"] for s in skills}
    role_ids = {r["role_id"] for r in roles}
    resource_ids = {r["resource_id"] for r in resources}
    misconception_ids = {m["misconception_id"] for m in misconceptions}
    item_ids = {i["item_id"] for i in items}

    # ---- 1. duplicate IDs ----
    check_duplicates(skills, "skill_id", "skill")
    check_duplicates(roles, "role_id", "role")
    check_duplicates(resources, "resource_id", "resource")
    check_duplicates(misconceptions, "misconception_id", "misconception")
    check_duplicates(items, "item_id", "assessment item")
    seen_edges = set()
    for e in edges:
        key = (e["from_skill"], e["to_skill"], e["type"])
        if key in seen_edges:
            err(f"Duplicate skill edge: {key}")
        seen_edges.add(key)

    # ---- 2. missing references ----
    for e in edges:
        if e["from_skill"] not in skill_ids:
            err(f"Edge references unknown from_skill: {e['from_skill']!r} ({e['type']})")
        if e["to_skill"] not in skill_ids:
            err(f"Edge references unknown to_skill: {e['to_skill']!r} ({e['type']})")

    for r in roles:
        for rs in r["required_skills"]:
            if rs["skill_id"] not in skill_ids:
                err(f"Role {r['role_id']!r} requires unknown skill: {rs['skill_id']!r}")

    for res in resources:
        for st in res["skill_targets"]:
            if st["skill_id"] not in skill_ids:
                err(f"Resource {res['resource_id']!r} targets unknown skill: {st['skill_id']!r}")
        for p in res["prerequisite_skill_ids"]:
            if p not in skill_ids:
                err(f"Resource {res['resource_id']!r} has unknown prerequisite skill: {p!r}")
        if not res["skill_targets"]:
            err(f"Resource {res['resource_id']!r} has no skill_targets")

    for m in misconceptions:
        if m["affected_skill"] not in skill_ids:
            err(f"Misconception {m['misconception_id']!r} has unknown affected_skill: {m['affected_skill']!r}")
        if m["root_prerequisite"] not in skill_ids:
            err(f"Misconception {m['misconception_id']!r} has unknown root_prerequisite: "
                f"{m['root_prerequisite']!r}")
        for rid in m["remediation_candidates"]:
            if rid not in resource_ids:
                err(f"Misconception {m['misconception_id']!r} has unknown remediation resource: {rid!r}")

    for it in items:
        if it["skill_id"] not in skill_ids:
            err(f"Item {it['item_id']!r} references unknown skill: {it['skill_id']!r}")
        key_count = sum(1 for o in it["options"] if o["is_key"])
        if key_count != 1:
            err(f"Item {it['item_id']!r} must have exactly one correct option, found {key_count}")
        for o in it["options"]:
            if o["misconception_id"] is not None and o["misconception_id"] not in misconception_ids:
                err(f"Item {it['item_id']!r} option tags unknown misconception: {o['misconception_id']!r}")

    # ---- demo dataset refs ----
    demo_dir = DATASET / "demo"
    if demo_dir.exists():
        demo_state = json.loads((demo_dir / "demo_learner_state.json").read_text(encoding="utf-8"))
        for ss in demo_state["skill_states"]:
            if ss["skill_id"] not in skill_ids:
                err(f"Demo learner state references unknown skill: {ss['skill_id']!r}")
        demo_scenario = json.loads((demo_dir / "demo_scenario.json").read_text(encoding="utf-8"))
        if demo_scenario["role_id"] not in role_ids:
            err(f"Demo scenario references unknown role: {demo_scenario['role_id']!r}")
        for sid in demo_scenario["seeded_graph_path"]:
            if sid not in skill_ids:
                err(f"Demo scenario seeded_graph_path references unknown skill: {sid!r}")
        if demo_scenario["seeded_misconception"]["misconception_id"] not in misconception_ids:
            err("Demo scenario seeded_misconception references unknown misconception")
        seeded_item_set = demo_scenario["seeded_item_set"]
        for group in ("backpropagation_items", "chain_rule_prereq_block_items", "misconception_tagged_items"):
            for iid in seeded_item_set[group]:
                if iid not in item_ids:
                    err(f"Demo scenario seeded_item_set[{group}] references unknown item: {iid!r}")
        items_by_id = {it["item_id"]: it for it in items}
        for ans in demo_scenario["scripted_attempt"]["answers"]:
            if ans["item_id"] not in item_ids:
                err(f"Demo scripted_attempt references unknown item: {ans['item_id']!r}")
                continue
            options = items_by_id[ans["item_id"]]["options"]
            if ans["chosen_is_key"]:
                if not any(o.get("is_key") for o in options):
                    err(f"Demo scripted_attempt: {ans['item_id']} has no key option")
            else:
                tag = ans.get("chosen_misconception_id")
                wrong = [o for o in options if not o.get("is_key")]
                if not wrong or (tag and not any(o.get("misconception_id") == tag for o in wrong)):
                    err(f"Demo scripted_attempt: {ans['item_id']} has no WRONG option tagged {tag!r} "
                        f"(the scripted attempt would not surface the intended misconception)")
    else:
        warn("data/dataset/demo/ not found — skipping demo dataset checks")

    # ---- 3. DAG check on hard PREREQUISITE_OF edges ----
    hard_adj = defaultdict(list)
    for e in edges:
        if e["type"] == "PREREQUISITE_OF" and e["strength"] == "hard":
            hard_adj[e["from_skill"]].append(e["to_skill"])

    WHITE, GRAY, BLACK = 0, 1, 2
    color = {s: WHITE for s in skill_ids}
    cycle_path = []

    def dfs(u, stack):
        color[u] = GRAY
        stack.append(u)
        for v in hard_adj.get(u, []):
            if color.get(v, WHITE) == GRAY:
                idx = stack.index(v)
                cycle_path.extend(stack[idx:] + [v])
                return True
            if color.get(v, WHITE) == WHITE:
                if dfs(v, stack):
                    return True
        stack.pop()
        color[u] = BLACK
        return False

    has_cycle = False
    for s in skill_ids:
        if color[s] == WHITE:
            if dfs(s, []):
                has_cycle = True
                break
    if has_cycle:
        err(f"Hard-prerequisite graph has a cycle: {' -> '.join(cycle_path)}")

    # ---- 4. orphan skills ----
    referenced = set()
    for e in edges:
        referenced.add(e["from_skill"])
        referenced.add(e["to_skill"])
    for r in roles:
        for rs in r["required_skills"]:
            referenced.add(rs["skill_id"])
    for res in resources:
        for st in res["skill_targets"]:
            referenced.add(st["skill_id"])
    for m in misconceptions:
        referenced.add(m["affected_skill"])
        referenced.add(m["root_prerequisite"])
    for it in items:
        referenced.add(it["skill_id"])

    orphans = skill_ids - referenced
    for o in sorted(orphans):
        err(f"Orphan skill (no edge, role requirement, resource, misconception or item references it): {o!r}")

    # ---- 5. role-required skills should have >= 1 resource ----
    skill_to_resources = defaultdict(list)
    for res in resources:
        for st in res["skill_targets"]:
            skill_to_resources[st["skill_id"]].append(res["resource_id"])

    for r in roles:
        for rs in r["required_skills"]:
            if not skill_to_resources.get(rs["skill_id"]):
                warn(f"Role {r['role_id']!r} requires skill {rs['skill_id']!r} with 0 catalog resources")

    # ---- 6. misconception root must be a hard-prerequisite ancestor of affected skill ----
    def hard_ancestors(skill_id):
        # reverse BFS over hard PREREQUISITE_OF edges
        rev = defaultdict(list)
        for e in edges:
            if e["type"] == "PREREQUISITE_OF" and e["strength"] == "hard":
                rev[e["to_skill"]].append(e["from_skill"])
        seen, stack = set(), [skill_id]
        while stack:
            cur = stack.pop()
            for p in rev.get(cur, []):
                if p not in seen:
                    seen.add(p)
                    stack.append(p)
        return seen

    for m in misconceptions:
        if m["affected_skill"] in skill_ids and m["root_prerequisite"] in skill_ids:
            if m["root_prerequisite"] == m["affected_skill"]:
                continue  # root can be the skill itself (e.g. a self-contained misconception)
            ancestors = hard_ancestors(m["affected_skill"])
            if m["root_prerequisite"] not in ancestors:
                warn(f"Misconception {m['misconception_id']!r}: root_prerequisite "
                     f"{m['root_prerequisite']!r} is not a hard-prerequisite ancestor of "
                     f"affected_skill {m['affected_skill']!r} (check the edge is curated correctly)")

    # ---- 7. already covered above (item skill/misconception refs) ----

    # ---- 8. resource URL sanity ----
    allowlist_domains = {
        "khanacademy.org", "3blue1brown.com", "developers.google.com", "docs.python.org",
        "realpython.com", "docs.pytest.org", "numpy.org", "pandas.pydata.org", "matplotlib.org",
        "seaborn.pydata.org", "kaggle.com", "scikit-learn.org", "pytorch.org", "d2l.ai",
        "cs231n.github.io", "cs231n.stanford.edu", "colah.github.io", "jalammar.github.io",
        "huggingface.co", "platform.openai.com", "mlflow.org", "docs.wandb.ai", "fastapi.tiangolo.com",
        "docs.evidentlyai.com", "developer.mozilla.org", "restfulapi.net", "expressjs.com", "jwt.io",
        "owasp.org", "redis.io", "rabbitmq.com", "martinfowler.com", "github.com", "docs.nginx.com",
        "learning.postman.com", "swagger.io", "graphql.org", "grpc.io", "stripe.com",
        "www.cloudflare.com", "12factor.net", "docs.docker.com", "kubernetes.io", "docs.github.com",
        "aws.amazon.com", "calculator.aws", "developer.hashicorp.com", "grafana.com", "git-scm.com",
        "google.github.io", "www.atlassian.com", "www.writethedocs.org", "www.thoughtspot.com",
        "www.klipfolio.com", "www.dataversity.net", "www.ftc.gov", "www.stitchdata.com",
        "cheatsheetseries.owasp.org", "support.microsoft.com", "exceljet.net", "help.tableau.com",
        "learn.microsoft.com", "hbr.org", "sqlbolt.com", "www.postgresql.org", "www.mongodb.com",
        "docs.sqlalchemy.org", "alembic.sqlalchemy.org", "www.databasestar.com",
        "docs.ultralytics.com", "www.freecodecamp.org", "www.bigocheatsheet.com",
        "www.geeksforgeeks.org", "refactoring.guru", "www.optimizely.com", "www.tensorflow.org",
        "shap.readthedocs.io", "docs.opencv.org", "ubuntu.com",
    }
    for res in resources:
        url = res["url"]
        parsed = urlparse(url)
        if parsed.scheme != "https" or not parsed.netloc:
            err(f"Resource {res['resource_id']!r} has a malformed/non-https URL: {url!r}")
            continue
        host = parsed.netloc.lower()
        bare_host = host[4:] if host.startswith("www.") else host
        if host not in allowlist_domains and bare_host not in allowlist_domains:
            warn(f"Resource {res['resource_id']!r} URL host {host!r} not in the reviewed allowlist — "
                 f"re-verify manually: {url}")
        if res["link_status"] not in ("ok", "redirected", "broken"):
            err(f"Resource {res['resource_id']!r} has invalid link_status: {res['link_status']!r}")

    # ---- 9. assessable-skill item coverage report (informational) ----
    assessable = [s for s in skills if s["assessable"]]
    items_by_skill = defaultdict(list)
    for it in items:
        items_by_skill[it["skill_id"]].append(it)
    zero, under_six, full = [], [], []
    for s in assessable:
        n = len(items_by_skill.get(s["skill_id"], []))
        if n == 0:
            zero.append(s["skill_id"])
        elif n < 6:
            under_six.append((s["skill_id"], n))
        else:
            full.append(s["skill_id"])

    # ---- report ----
    print(f"Skills: {len(skills)} | Roles: {len(roles)} | Edges: {len(edges)} | "
          f"Resources: {len(resources)} | Misconceptions: {len(misconceptions)} | Items: {len(items)}")
    print()
    print("Item-bank coverage (informational, not a hard gate this phase):")
    print(f"  Assessable skills with >=6 items : {len(full)}")
    print(f"  Assessable skills with 1-5 items : {len(under_six)}")
    print(f"  Assessable skills with 0 items   : {len(zero)}")
    print()

    if WARNINGS:
        print(f"WARNINGS ({len(WARNINGS)}):")
        for w in WARNINGS:
            print(f"  - {w}")
        print()

    if ERRORS:
        print(f"ERRORS ({len(ERRORS)}):")
        for e in ERRORS:
            print(f"  - {e}")
        print()
        print("VALIDATION FAILED")
        sys.exit(1)

    print("VALIDATION PASSED (0 hard errors)")
    sys.exit(0)


if __name__ == "__main__":
    main()
